"""Shared loader and helpers for the RFA skill decision tools.

No network access and no environment reads: everything comes from rfa_data.json (generated by
tools/build_skill_data.py) and disclosure/templates.json.
"""

import difflib
import json
import pathlib
import sys

SKILL_ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA_PATH = SKILL_ROOT / "data" / "rfa_data.json"
TEMPLATES_PATH = SKILL_ROOT / "disclosure" / "templates.json"

AI_USE_KINDS = ("none", "language_editing", "generative_content", "research_conduct")
# Source of data["ai_policies"]; rules that say resolve_from point here.
REGISTRY_SOURCE = "rfa-core/06-ai-disclosure/policy-registry.yaml"
CONFIDENCE_RANK = {"high": 0, "medium": 1, "low": 2}
METHODS_CODES = ("methods", "materials_and_methods", "methodology")

# kind -> top-level collection in rfa_data.json
ID_KINDS = {
    "discipline": "disciplines",
    "document_type": "document_types",
    "standard": "standards",
    "study_design": "study_designs",
    "reporting_guideline": "reporting_guidelines",
    "policy": "ai_policies",
}


def load_data(path=None) -> dict:
    """Load rfa_data.json (default: ../data/rfa_data.json relative to this file)."""
    p = pathlib.Path(path) if path else DATA_PATH
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f)


def load_templates(path=None) -> dict:
    """Load the bilingual disclosure templates."""
    p = pathlib.Path(path) if path else TEMPLATES_PATH
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f)


def known_ids(kind: str, data: dict) -> list:
    """Return the sorted list of valid ids for a kind."""
    if kind == "language":
        return sorted(data["languages"]["languages"])
    return sorted(data[ID_KINDS[kind]])


def suggest(value: str, candidates, n: int = 5, cutoff: float = 0.6) -> list:
    """Close matches for value among candidate ids, also comparing last path segments."""
    value = (value or "").strip().lower()
    by_segment = {}
    for c in candidates:
        by_segment.setdefault(c.rsplit("/", 1)[-1], []).append(c)
    hits = []
    for m in difflib.get_close_matches(value, list(candidates), n=n, cutoff=cutoff):
        hits.append(m)
    last = value.rsplit("/", 1)[-1]
    for seg in difflib.get_close_matches(last, list(by_segment), n=n, cutoff=cutoff):
        hits.extend(by_segment[seg])
    out = []
    for h in hits:
        if h not in out:
            out.append(h)
    return out[:n]


def resolve_id(kind: str, value, data: dict):
    """Resolve value to a full id of the given kind.

    Accepts a full id (case-insensitive) or a unique last segment (for example "psychology").
    Returns the full id as a string, or a list of suggestions (possibly empty) when the value is
    unknown or ambiguous. A discipline area returns its leaves as suggestions.
    """
    ids = known_ids(kind, data)
    v = str(value).strip().lower()
    if v in ids:
        return v
    matches = [i for i in ids if i.rsplit("/", 1)[-1] == v]
    if len(matches) == 1:
        return matches[0]
    if matches:
        return matches
    if kind == "discipline":
        leaves = [i for i in ids if data["disciplines"][i]["area"] == v]
        if leaves:
            return leaves
    return suggest(v, ids)


def parse_language(value, data: dict):
    """Split a language tag into (language, variant).

    "es" -> ("es", None); "es-CO" -> ("es", "es-CO"); "pt-BR" -> ("pt-br", None) because pt-br is
    a language id of its own. Returns (None, None) for an unknown base language.
    """
    langs = data["languages"]["languages"]
    tag = str(value).strip().replace("_", "-")
    if tag.lower() in langs:
        return tag.lower(), None
    base, sep, region = tag.partition("-")
    if sep and base.lower() in langs and region:
        return base.lower(), f"{base.lower()}-{region.upper()}"
    return None, None


def csl_style_key(standard_id: str, variant, data: dict):
    """Return the STYLE_MAP key for a standard (and variant), or None when there is none."""
    keys = data["standards"][standard_id]["csl_style_keys"]
    if standard_id in keys:
        return standard_id
    if variant and f"{standard_id}:{variant}" in keys:
        return f"{standard_id}:{variant}"
    return None


def disclosure_requirement(policy_entry: dict, kind: str):
    """Return (required, placements) for an AI-use kind under a policy-registry entry.

    required is True, False or "conditional". placements are registry location codes.
    """
    locations = list(policy_entry.get("locations") or [])
    if kind == "none":
        return False, []
    if kind == "research_conduct":
        if policy_entry.get("research_conduct") != "disclose":
            return False, []
        return True, [c for c in locations if c in METHODS_CODES] or ["methods"]
    if kind == "generative_content":
        return True, locations
    if kind == "language_editing":
        wa = policy_entry.get("writing_assistance")
        if wa == "disclose":
            return True, locations
        if wa == "disclose_if_generative":
            return "conditional", locations
        if wa == "not_required":
            return False, []
        raise ValueError(f"unknown writing_assistance value: {wa!r}")
    raise ValueError(f"unknown AI-use kind: {kind!r}")


def dedupe(items) -> list:
    """Remove duplicates while keeping the first occurrence order."""
    out = []
    for it in items:
        if it not in out:
            out.append(it)
    return out


def write_json(obj) -> None:
    """Write obj as UTF-8 JSON to stdout, independent of the console encoding."""
    text = json.dumps(obj, indent=2, ensure_ascii=False) + "\n"
    buffer = getattr(sys.stdout, "buffer", None)
    if buffer is not None:
        sys.stdout.flush()
        buffer.write(text.encode("utf-8"))
        buffer.flush()
    else:
        sys.stdout.write(text)
